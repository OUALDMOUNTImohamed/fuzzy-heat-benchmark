def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--outdir", default="results", type=Path)
    p.add_argument("--quick", action="store_true", help="coarse grids for a fast run")
    p.add_argument("--only", nargs="+", choices=list(EXPERIMENTS), help="run selected experiments")
    p.add_argument("--selftest", action="store_true", help="regression against the manuscript")
    p.add_argument("--show", action="store_true", help="also display each figure (Spyder Plots pane)")
    args = p.parse_args(argv)

    if args.selftest:
        sys.exit(0 if selftest() else 1)

    out = Output(args.outdir)
    names = args.only or list(EXPERIMENTS)
    t_start = time.perf_counter()
    timings = {}
    for name in names:
        log(f"[{name}]")
        t0 = time.perf_counter()
        EXPERIMENTS[name](out, args.quick)
        timings[name] = round(time.perf_counter() - t0, 2)
        log(f"  done in {timings[name]:.1f} s")

    out.summary["settings"] = dict(kappa=KAPPA, lambda_=LAM, T=T_FINAL, x=X_MID,
                                   A_tilde=[A_TILDE.lo, A_TILDE.mode, A_TILDE.hi],
                                   quick=args.quick, experiments=names)
    out.summary["timings_s"] = timings
    out.summary["environment"] = dict(python=sys.version.split()[0], numpy=np.__version__,
                                      scipy=__import__("scipy").__version__,
                                      matplotlib=matplotlib.__version__, platform=platform.platform())
    (args.outdir / "summary.json").write_text(json.dumps(out.summary, indent=2, default=float))
    log(f"Finished in {time.perf_counter() - t_start:.1f} s; results in {args.outdir.resolve()}")


if __name__ == "__main__":
    main()
