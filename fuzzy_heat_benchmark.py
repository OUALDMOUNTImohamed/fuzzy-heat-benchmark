# 6. Regression tests against the values printed in the manuscript
# ----------------------------------------------------------------------------
def selftest() -> bool:
    ok = True

    def check(label, got, ref, tol):
        nonlocal ok
        got, ref = np.atleast_1d(got), np.atleast_1d(ref)
        err = float(np.max(np.abs(got - ref)))
        good = err <= tol
        ok &= good
        print(f"  [{'PASS' if good else 'FAIL'}] {label:55s} err={err:.2e} (tol {tol:.0e})")

    def cut(F, alpha, idx=0):
        lo, hi = A_TILDE.cut(alpha)
        r = batched_cuts(F, [idx], [lo], [hi])
        return [r.lower[0], r.upper[0]]

    print("Regression against the manuscript")
    check("Table 2, affine alpha=0.5", cut(G_exact(CORR["affine"], [0.5]), 0.5), [0.129433, 0.208367], 1e-6)
    check("Table 2, quadratic alpha=0", cut(G_exact(CORR["quadratic"], [0.5]), 0.0), [0.035341, 0.610524], 1e-6)
    check("Table 2, reciprocal alpha=0.25", cut(G_exact(CORR["reciprocal"], [0.5]), 0.25),
          [0.842282, 2.298263], 1e-6)
    check("Table 3, quadratic t=0.1 alpha=0 (interior max)", cut(G_exact(CORR["quadratic"], [0.1]), 0.0),
          [0.906018, 1.365174], 1e-6)
    lo, hi = A_TILDE.cut(0.25)
    check("Fig. 2, independent enclosure alpha=0.25",
          [lo * np.exp(-LAM * 0.5 * hi ** 2), hi * np.exp(-LAM * 0.5 * lo ** 2)], [0.029933, 1.271933], 1e-6)

    # Table 4, first row
    alphas = np.linspace(0, 1, 101); lo, hi = A_TILDE.cut(alphas)
    h, N = 1 / 20, 400
    ex = batched_cuts(G_exact(CORR["quadratic"], [0.5]), np.zeros(101, int), lo, hi)
    nu = batched_cuts(G_explicit_modal(CORR["quadratic"], h, 0.5 / N, [N]), np.zeros(101, int), lo, hi)
    check("Table 4, M_x=20 fuzzy error", np.max(hausdorff(ex.lower, ex.upper, nu.lower, nu.upper)),
          6.5351e-4, 5e-8)

    # modal closed form vs full explicit FD
    x = np.linspace(0, 1, 21)
    a = np.linspace(1, 3, 7)
    U = explicit_fd(np.sin(np.pi * x), a, CORR["quadratic"].f, h, 0.5 / N, N)
    Gm = G_explicit_modal(CORR["quadratic"], h, 0.5 / N, [N])(a)[0]
    check("Modal closed form = full explicit FD", U, Gm[:, None] * np.sin(np.pi * x)[None, :], 1e-13)

    # Table 5
    xs = 0.5
    def F_nm(aa):
        aa = np.atleast_1d(aa); b = aa ** 2
        return (aa * (np.exp(-LAM * b * 0.1) * np.sin(np.pi * xs)
                      + 0.35 * np.exp(-9 * LAM * b * 0.1) * np.sin(3 * np.pi * xs)))[None, :]
    check("Table 5, non-modal x=0.5 alpha=0", cut(F_nm, 0.0), [0.762039, 1.357197], 1e-6)

    # Mittag-Leffler quadrature vs high-precision series
    try:
        import mpmath as mp
        mp.mp.dps = 60
        for beta in (0.6, 0.8):
            xx = np.array([0.0, 0.1, 0.5, 1.0, 2.0, 4.0, 6.5])
            ref = [float(mp.nsum(lambda k: (-mp.mpf(v)) ** k / mp.gamma(beta * k + 1), [0, mp.inf]))
                   for v in xx]
            check(f"Mittag-Leffler quadrature, beta={beta}", mittag_leffler_neg(beta, xx), ref, 1e-12)
    except ImportError:
        print("  [SKIP] mpmath not installed; Mittag-Leffler check skipped")

    # Table 7 (fractional)
    check("Table 7, exact beta=0.6 alpha=0", cut(H_exact(CORR["quadratic"], 0.6, [0.5]), 0.0),
          [0.242326, 0.536660], 1e-6)
    check("Table 7, exact beta=0.8 alpha=0.5", cut(H_exact(CORR["quadratic"], 0.8, [0.5]), 0.5),
          [0.226274, 0.466484], 1e-6)
    mesh = np.linspace(0, 0.5, 401)
    F_l1 = H_L1_modal(CORR["quadratic"], 0.6, mesh, mu_h(1 / 200), [400])
    check("Table 7, L1 beta=0.6 alpha=0 (Mx=200, N=400)", cut(F_l1, 0.0), [0.242524, 0.536884], 2e-6)
    print("ALL PASSED" if ok else "SOME CHECKS FAILED")
    return ok


