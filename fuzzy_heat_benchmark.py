class Output:
    def __init__(self, root: Path):
        self.root = root
        (root / "tables").mkdir(parents=True, exist_ok=True)
        (root / "figures").mkdir(parents=True, exist_ok=True)
        self.summary: dict = {}

    def csv(self, name, header, rows):
        with open(self.root / "tables" / f"{name}.csv", "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(header)
            w.writerows(rows)

    def latex(self, name, caption, label, header, rows, colspec=None, size=r"\small"):
        colspec = colspec or "c" * len(header)
        lines = [r"\begin{table}[htbp]", r"\centering",
                 rf"\caption{{{caption}}}", rf"\label{{{label}}}", size,
                 rf"\begin{{tabular}}{{{colspec}}}", r"\toprule",
                 " & ".join(header) + r"\\", r"\midrule"]
        for r in rows:
            lines.append(r"\midrule" if r == "MIDRULE" else " & ".join(map(str, r)) + r"\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
        (self.root / "tables" / f"{name}.tex").write_text("\n".join(lines) + "\n")

    def fig(self, fig, name):
        for ext in ("pdf", "png"):
            fig.savefig(self.root / "figures" / f"{name}.{ext}")
        if SHOW:
            plt.show()          # displayed in Spyder's Plots pane / a window
        plt.close(fig)


def sci(x, d=3):
    """LaTeX scientific notation."""
    if x == 0 or not np.isfinite(x):
        return r"\(0\)" if x == 0 else "--"
    e = int(math.floor(math.log10(abs(x))))
    return rf"\({x / 10 ** e:.{d}f}\times10^{{{e}}}\)"


def _err_cell(e, u):
    """Absolute and relative error for a table cell; exact zeros stay '0'."""
    if e < 1e-12:
        return "0"
    rel = 100 * e / u
    if rel >= 0.1:
        return f"{e:.4f} ({rel:.1f}\\%)"
    return f"{sci(e, 1)} ({rel:.1g}\\%)"


def interval(l, u, d=6):
    return f"[{l:.{d}f}, {u:.{d}f}]"


def log(msg):
    print(msg, flush=True)


