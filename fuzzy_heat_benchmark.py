def exp_width(out: Output, quick: bool):
    """Width ratio (independent rectangular enclosure) / (exact correlated cut)."""
    nt, na = (40, 21) if quick else (120, 51)
    times = np.linspace(0.02, 1.0, nt)
    alphas = np.linspace(0.0, 0.96, na)
    figs = {}
    rows_tex, rows_csv = [], []
    for name in ("affine", "quadratic", "reciprocal"):
        corr = CORR[name]
        F = G_exact(corr, times)
        Ti, Ai = np.meshgrid(np.arange(nt), np.arange(na), indexing="ij")
        lo, hi = A_TILDE.cut(alphas[Ai.ravel()])
        cr = batched_cuts(F, Ti.ravel(), lo, hi)
        b1, b2 = corr.f(lo), corr.f(hi)
        bl, bu = np.minimum(b1, b2), np.maximum(b1, b2)
        tt = times[Ti.ravel()]
        ind_w = hi * np.exp(-LAM * tt * bl) - lo * np.exp(-LAM * tt * bu)
        ratio = (ind_w / (cr.upper - cr.lower)).reshape(nt, na)
        figs[name] = ratio
        for t in (0.1, 0.5, 1.0):
            i = int(np.argmin(np.abs(times - t)))
            for a_ in (0.0, 0.25, 0.5):
                j = int(np.argmin(np.abs(alphas - a_)))
                rows_csv.append([name, times[i], alphas[j], ratio[i, j]])
        out.summary[f"width_ratio_max_{name}"] = float(np.nanmax(ratio))
    # table: evaluated exactly at the stated (t, alpha), not at grid neighbours
    def ratio_at(name, t, a_):
        corr = CORR[name]
        lo_, hi_ = A_TILDE.cut(a_)
        c = batched_cuts(G_exact(corr, [t]), [0], [lo_], [hi_])
        b1, b2 = corr.f(lo_), corr.f(hi_)
        bl_, bu_ = min(b1, b2), max(b1, b2)
        w_ind = hi_ * np.exp(-LAM * t * bl_) - lo_ * np.exp(-LAM * t * bu_)
        return float(w_ind / (c.upper[0] - c.lower[0]))

    rows_csv = []
    for t in (0.1, 0.5, 1.0):
        row = [f"{t:.1f}"]
        for name in ("affine", "quadratic", "reciprocal"):
            for a_ in (0.0, 0.5):
                r_ = ratio_at(name, t, a_)
                row.append(f"{r_:.2f}")
                rows_csv.append([name, t, a_, r_])
        rows_tex.append(row)
    out.latex("tab_width_ratio",
              r"Width ratio of the noninteractive enclosure to the exact correlated cut at \(x=1/2\).",
              "tab:width-ratio",
              [r"\(t\)", r"aff. \(\alpha=0\)", r"aff. \(\alpha=0.5\)", r"quad. \(\alpha=0\)",
               r"quad. \(\alpha=0.5\)", r"rec. \(\alpha=0\)", r"rec. \(\alpha=0.5\)"], rows_tex)
    out.csv("tab_width_ratio", ["f", "t", "alpha", "ratio"], rows_csv)

    # check of the value quoted in Section 5.1 (alpha = 0.25, t = 0.5, quadratic)
    lo, hi = A_TILDE.cut(0.25)
    cr = batched_cuts(G_exact(CORR["quadratic"], [0.5]), [0], [lo], [hi])
    ind = hi * np.exp(-LAM * 0.5 * lo ** 2) - lo * np.exp(-LAM * 0.5 * hi ** 2)
    r = ind / (cr.upper[0] - cr.lower[0])
    out.summary["width_ratio_section5_alpha025_t05"] = float(r)
    log(f"  width ratio (quadratic, alpha=0.25, t=0.5) = {r:.4f}  [paper states 2.39]")

    # For decreasing f the noninteractive enclosure coincides with the correlated
    # cut (ratio = 1 up to rounding), so only the increasing laws are plotted.
    out.summary["width_ratio_reciprocal_max_dev_from_1"] = float(np.nanmax(np.abs(figs["reciprocal"] - 1)))
    from matplotlib.colors import LogNorm
    vmax = max(np.nanmax(figs["affine"]), np.nanmax(figs["quadratic"]))
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, name in zip(axes, ("affine", "quadratic")):
        pm = ax.pcolormesh(alphas, times, figs[name], shading="auto", cmap="magma",
                           norm=LogNorm(vmin=1.0, vmax=vmax))
        cs = ax.contour(alphas, times, figs[name], levels=[2, 5, 10, 50], colors="w", linewidths=0.7)
        ax.clabel(cs, fmt="%g", fontsize=7)
        fig.colorbar(pm, ax=ax, label="width ratio (log scale)")
        ax.set_title(rf"$f(a)={CORR[name].tex}$"); ax.set_xlabel(r"$\alpha$"); ax.grid(False)
    axes[0].set_ylabel(r"$t$")
    out.fig(fig, "fig_width_ratio")


def exp_cost(out: Output, quick: bool):
    """Cost of certified extrema vs. endpoint-only rule, and the accuracy gained."""
    alphas = np.linspace(0, 1, 101)
    lo, hi = A_TILDE.cut(alphas)
    rows_tex, rows_csv = [], []
    for t in (0.10, 0.15, 0.20, 0.50):
        corr = CORR["quadratic"]
        g = lambda a: a * np.exp(-LAM * t * corr.f(a))  # noqa: E731
        # (i) per-level bounded scalar optimisation (as in the original Section 8)
        nfev, t0 = 0, time.perf_counter()
        ex_lo, ex_hi = np.empty(101), np.empty(101)
        for k in range(101):
            if hi[k] - lo[k] < 1e-15:
                ex_lo[k] = ex_hi[k] = g(lo[k]); nfev += 1
                continue
            r1 = minimize_scalar(lambda a: g(a), bounds=(lo[k], hi[k]), method="bounded",
                                 options={"xatol": 1e-13})
            r2 = minimize_scalar(lambda a: -g(a), bounds=(lo[k], hi[k]), method="bounded",
                                 options={"xatol": 1e-13})
            cand = [g(lo[k]), g(hi[k]), r1.fun, -r2.fun]
            ex_lo[k], ex_hi[k] = min(cand), max(cand)
            nfev += r1.nfev + r2.nfev + 2
        t_scipy = time.perf_counter() - t0
        # (ii) batched dense-grid + golden refinement (this file)
        t0 = time.perf_counter()
        cr = batched_cuts(G_exact(corr, [t]), np.zeros(101, int), lo, hi)
        t_batch = time.perf_counter() - t0
        # (iii) endpoint-only (invalid in general)
        e_lo = np.minimum(g(lo), g(hi)); e_hi = np.maximum(g(lo), g(hi))
        err = hausdorff(cr.lower, cr.upper, e_lo, e_hi)
        agree = float(np.max(hausdorff(cr.lower, cr.upper, ex_lo, ex_hi)))
        rel = 100 * np.max(err / cr.upper)
        rows_tex.append([f"{t:.2f}", f"{nfev}", f"{t_scipy * 1e3:.1f}", f"{cr.n_evals}",
                         f"{t_batch * 1e3:.1f}", "202", sci(err.max(), 2),
                         f"{rel:.1f}\\%" if rel >= 0.1 else f"{rel:.1g}\\%"])
        rows_csv.append([t, nfev, t_scipy, cr.n_evals, t_batch, 202, err.max(), agree])
        log(f"  t={t:.2f}: scipy {nfev} evals, batched {cr.n_evals} evals, "
            f"endpoint-only max error {err.max():.3e}, solvers agree to {agree:.1e}")
    out.latex("tab_cost",
              r"Cost of certified cut extrema for 101 levels (\(f(a)=a^2\), \(x=1/2\)) and the endpoint-only error it removes. "
              r"Timings are machine dependent; evaluation counts are portable.",
              "tab:cost",
              [r"\(t\)", "bounded evals", "ms", "batched evals", "ms", "endpoint evals",
               "max error removed", "rel."], rows_tex, size=r"\footnotesize")
    out.csv("tab_cost", ["t", "scipy_evals", "scipy_s", "batched_evals", "batched_s",
                         "endpoint_evals", "endpoint_max_err", "solver_agreement"], rows_csv)


