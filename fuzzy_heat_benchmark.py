# 3. Exact and discrete parameter-to-solution maps
# ----------------------------------------------------------------------------
def G_exact(corr: Correlation, times, mu=np.pi ** 2):
    """a -> a exp(-kappa mu f(a) t) for every t in `times`; shape (T, P)."""
    times = np.atleast_1d(np.asarray(times, float))

    def F(a):
        a = np.atleast_1d(a)
        return a[None, :] * np.exp(-KAPPA * mu * np.outer(times, corr.f(a)))
    return F


def G_explicit_modal(corr: Correlation, h: float, tau: float, steps):
    """Discrete amplitude of the explicit scheme for the modal datum:
    a [1 - tau kappa f(a) mu_h]^n (the discrete sine vector is an eigenvector)."""
    steps = np.atleast_1d(np.asarray(steps, int))
    m = mu_h(h)

    def F(a):
        a = np.atleast_1d(a)
        q = 1.0 - tau * KAPPA * corr.f(a) * m
        return a[None, :] * q[None, :] ** steps[:, None]
    return F


def explicit_fd(phi: np.ndarray, a: np.ndarray, f: Callable, h: float,
                tau: float, n_steps: int) -> np.ndarray:
    """Full explicit finite-difference solve, vectorised over latent values.
    Returns U of shape (P, Mx+1) at step n_steps."""
    a = np.atleast_1d(a)
    b = f(a)                                   # paired coefficient, same latent a
    r = KAPPA * b * tau / h ** 2
    if r.max() > 0.5 + 1e-14:
        raise ValueError(f"CFL violated: max r = {r.max():.4f} > 1/2")
    U = a[:, None] * phi[None, :]
    U[:, 0] = U[:, -1] = 0.0
    rr = r[:, None]
    for _ in range(n_steps):
        U[:, 1:-1] = U[:, 1:-1] + rr * (U[:, 2:] - 2.0 * U[:, 1:-1] + U[:, :-2])
    return U


# --- Mittag-Leffler function -------------------------------------------------
_GL_CACHE: dict = {}


def mittag_leffler_neg(beta: float, x, n_nodes: int = 600, chunk: int = 4096):
    """E_beta(-x) for 0 < beta <= 1 and x >= 0, vectorised and cancellation-free.

    Uses the completely-monotone representation
      E_beta(-x) = sin(beta pi)/(beta pi) *
                   int_0^{pi/2} exp(-(x tan th)^{1/beta}) / (1 + cos(beta pi) sin 2th) dth,
    obtained from E_beta(-s^beta) = int_0^inf e^{-rs} K_beta(r) dr by the
    substitutions r = u^{1/beta}, u = tan th. The integrand is bounded, so
    Gauss-Legendre quadrature is accurate to ~1e-14 (checked in --selftest).
    """
    x = np.asarray(x, dtype=float)
    if beta == 1.0:
        return np.exp(-x)
    key = (n_nodes, beta)
    if key not in _GL_CACHE:
        z, w = np.polynomial.legendre.leggauss(n_nodes)
        th = (z + 1.0) * np.pi / 4.0
        w = w * np.pi / 4.0
        den = 1.0 + np.cos(beta * np.pi) * np.sin(2.0 * th)
        _GL_CACHE[key] = (np.tan(th), w / den)
    tn, wd = _GL_CACHE[key]
    flat = x.ravel()
    out = np.empty_like(flat)
    p = 1.0 / beta
    for s in range(0, flat.size, chunk):
        xs = flat[s:s + chunk, None]
        out[s:s + chunk] = np.exp(-(xs * tn[None, :]) ** p) @ wd
    return (out * np.sin(beta * np.pi) / (beta * np.pi)).reshape(x.shape)


def H_exact(corr: Correlation, beta: float, times, mu=np.pi ** 2):
    """a -> a E_beta(-kappa mu f(a) t^beta); shape (T, P)."""
    times = np.atleast_1d(np.asarray(times, float))

    def F(a):
        a = np.atleast_1d(a)
        arg = KAPPA * mu * np.outer(times ** beta, corr.f(a))
        return a[None, :] * mittag_leffler_neg(beta, arg)
    return F


def H_L1_modal(corr: Correlation, beta: float, mesh: np.ndarray, mu: float, keep):
    """Implicit L1 scheme on an arbitrary temporal mesh for the modal datum.

    sum_{k=1}^n w_{n,k} (U^k - U^{k-1}) = -kappa f(a) mu U^n,
    w_{n,k} = [(t_n - t_{k-1})^{1-beta} - (t_n - t_k)^{1-beta}] / (tau_k Gamma(2-beta)).
    On a uniform mesh this is exactly scheme (9.6)-(9.7) of the paper.
    Returns a callable a -> array (len(keep), P)."""
    keep = np.atleast_1d(np.asarray(keep, int))
    N = mesh.size - 1
    tau = np.diff(mesh)
    g2 = Gamma(2.0 - beta)
    W = []                                     # precompute weight rows once
    for n in range(1, N + 1):
        tn = mesh[n]
        W.append(((tn - mesh[:n]) ** (1 - beta) - (tn - mesh[1:n + 1]) ** (1 - beta))
                 / tau[:n] / g2)
    pos = {int(n): i for i, n in enumerate(keep)}

    def F(a):
        a = np.atleast_1d(a)
        c = KAPPA * corr.f(a) * mu
        out = np.empty((keep.size, a.size))
        if 0 in pos:
            out[pos[0]] = a
        dU = np.empty((N, a.size))
        U_prev = a.astype(float).copy()
        for n in range(1, N + 1):
            w = W[n - 1]
            hist = w[:n - 1] @ dU[:n - 1] if n > 1 else 0.0
            U = (w[n - 1] * U_prev - hist) / (w[n - 1] + c)
            dU[n - 1] = U - U_prev
            U_prev = U
            if n in pos:
                out[pos[n]] = U
        return out
    return F


