@dataclass(frozen=True)
class TriangularFuzzy:
    """Triangular fuzzy number (lo, mode, hi)."""
    lo: float = 1.0
    mode: float = 2.0
    hi: float = 3.0

    def cut(self, alpha):
        alpha = np.asarray(alpha, dtype=float)
        return (self.lo + alpha * (self.mode - self.lo),
                self.hi - alpha * (self.hi - self.mode))


@dataclass(frozen=True)
class Correlation:
    """Continuous, injective, monotone correlation law b = f(a)."""
    name: str
    f: Callable[[np.ndarray], np.ndarray]
    df: Callable[[np.ndarray], np.ndarray]
    tex: str
    increasing: bool


CORR = {
    "affine": Correlation("affine", lambda a: 2.0 * a + 1.0,
                          lambda a: 2.0 + 0.0 * np.asarray(a), r"2a+1", True),
    "quadratic": Correlation("quadratic", lambda a: np.asarray(a) ** 2,
                             lambda a: 2.0 * np.asarray(a), r"a^2", True),
    "reciprocal": Correlation("reciprocal", lambda a: 1.0 / np.asarray(a),
                              lambda a: -1.0 / np.asarray(a) ** 2, r"1/a", False),
}

A_TILDE = TriangularFuzzy()


def mu_h(h: float) -> float:
    """Eigenvalue of the negative centred second difference for sin(pi x)."""
    return 4.0 / h ** 2 * np.sin(np.pi * h / 2.0) ** 2


# ----------------------------------------------------------------------------
# 2. Batched global 1-D optimiser over latent cuts
# ----------------------------------------------------------------------------
@dataclass
class CutResult:
    lower: np.ndarray
    upper: np.ndarray
    arg_lower: np.ndarray
    arg_upper: np.ndarray
    interior_lower: np.ndarray
    interior_upper: np.ndarray
    n_evals: int


def batched_cuts(F: Callable[[np.ndarray], np.ndarray],
                 out_idx: Sequence[int],
                 lo: Sequence[float],
                 hi: Sequence[float],
                 n_grid: int = 2001,
                 golden_iter: int = 30) -> CutResult:
    """Global min and max of p_k(a) = F(a)[out_idx[k]] on [lo_k, hi_k] for all k.

    F maps latent values a (shape (P,)) to an array of shape (n_out, P): one
    row per output (a time level, a spatial node, ...). It must be continuous
    in a; nothing else (monotonicity, differentiability) is assumed.

    Algorithm
      1. Evaluate F once on a common dense grid that contains every cut
         endpoint exactly, so both endpoints are always candidates.
      2. For every grid extremum lying strictly inside its cut, refine by a
         golden-section search on the two adjacent grid cells. All refinements
         are vectorised: each golden step is a single call of F.
    The returned value is never worse than the best grid value.
    """
    out_idx = np.asarray(out_idx, dtype=int)
    lo = np.asarray(lo, dtype=float)
    hi = np.asarray(hi, dtype=float)
    K = out_idx.size

    grid = np.unique(np.concatenate([np.linspace(lo.min(), hi.max(), n_grid), lo, hi]))
    V = F(grid)
    n_evals = grid.size

    lower = np.empty(K); upper = np.empty(K)
    a_low = np.empty(K); a_up = np.empty(K)
    int_low = np.zeros(K, bool); int_up = np.zeros(K, bool)
    refine = []                         # (task, sense, left, right)

    for k in range(K):
        i0 = np.searchsorted(grid, lo[k])
        i1 = np.searchsorted(grid, hi[k])
        v = V[out_idx[k], i0:i1 + 1]
        jmin, jmax = int(np.argmin(v)), int(np.argmax(v))
        lower[k], a_low[k] = v[jmin], grid[i0 + jmin]
        upper[k], a_up[k] = v[jmax], grid[i0 + jmax]
        if 0 < jmax < v.size - 1:
            int_up[k] = True
            refine.append((k, +1.0, grid[i0 + jmax - 1], grid[i0 + jmax + 1]))
        if 0 < jmin < v.size - 1:
            int_low[k] = True
            refine.append((k, -1.0, grid[i0 + jmin - 1], grid[i0 + jmin + 1]))

    if refine:
        kk = np.array([r[0] for r in refine], dtype=int)
        sg = np.array([r[1] for r in refine])
        L = np.array([r[2] for r in refine])
        R = np.array([r[3] for r in refine])
        rows, cols = out_idx[kk], np.arange(kk.size)
        g = (np.sqrt(5.0) - 1.0) / 2.0

        def obj(x):                      # maximise sg * p_k
            return sg * F(x)[rows, cols]

        c = R - g * (R - L); d = L + g * (R - L)
        fc, fd = obj(c), obj(d)
        n_evals += 2 * kk.size
        for _ in range(golden_iter):
            left = fc > fd
            Ln = np.where(left, L, c); Rn = np.where(left, d, R)
            cn = np.where(left, Rn - g * (Rn - Ln), d)
            dn = np.where(left, c, Ln + g * (Rn - Ln))
            fe = obj(np.where(left, cn, dn))
            n_evals += kk.size
            fc, fd = np.where(left, fe, fd), np.where(left, fc, fe)
            L, R, c, d = Ln, Rn, cn, dn
        best = np.maximum(fc, fd)
        xbest = np.where(fc > fd, c, d)
        for j, k in enumerate(kk):
            val = sg[j] * best[j]
            if sg[j] > 0 and val > upper[k]:
                upper[k], a_up[k] = val, xbest[j]
            elif sg[j] < 0 and val < lower[k]:
                lower[k], a_low[k] = val, xbest[j]

    return CutResult(lower, upper, a_low, a_up, int_low, int_up, n_evals)


def hausdorff(l1, u1, l2, u2):
    """Hausdorff distance between intervals [l1,u1] and [l2,u2] (vectorised)."""
    return np.maximum(np.abs(np.asarray(l1) - l2), np.abs(np.asarray(u1) - u2))


