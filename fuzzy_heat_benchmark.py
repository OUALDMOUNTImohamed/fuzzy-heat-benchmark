        a = np.atleast_1d(a)
        b = corr.f(a)
        return a[None, :] * (np.exp(-LAM * b * t)[None, :] * np.sin(np.pi * xs)[:, None]
                             + 0.35 * np.exp(-9 * LAM * b * t)[None, :] * np.sin(3 * np.pi * xs)[:, None])

